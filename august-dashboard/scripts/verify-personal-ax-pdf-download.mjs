import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const panelPath = fileURLToPath(new URL('../src/PersonalAxReportPanel.tsx', import.meta.url))
const appPath = fileURLToPath(new URL('../src/App.tsx', import.meta.url))
const generatorPath = fileURLToPath(new URL('./generate-personal-ax-pdf.mjs', import.meta.url))
const packagePath = fileURLToPath(new URL('../package.json', import.meta.url))
const [panelSource, appSource, generatorSource, packageSource] = await Promise.all([
  readFile(panelPath, 'utf8'), readFile(appPath, 'utf8'), readFile(generatorPath, 'utf8'), readFile(packagePath, 'utf8'),
])
const packageJson = JSON.parse(packageSource)

assert.equal(packageJson.devDependencies?.playwright, '^1.58.2', 'build-time PDF generation needs Playwright as a development dependency')
assert.equal(packageJson.scripts?.['generate:personal-ax-pdf'], 'node scripts/generate-personal-ax-pdf.mjs', 'the PDF generator must be executable through npm')
assert.match(packageJson.scripts?.['build:public'] ?? '', /generate:personal-ax-pdf/, 'the Pages build must include the static PDF')
assert.doesNotMatch(panelSource, /window\.print\s*\(/, 'direct PDF download must not invoke the browser print dialog')
assert.doesNotMatch(panelSource, /import\('html2canvas'\)|import\('jspdf'\)/, 'the long report must not invoke memory-heavy client canvas rendering')
assert.match(panelSource, /report\.id === 'designer-ai-exposure'/, 'the long designer report needs a dedicated static PDF link')
assert.match(panelSource, /downloads\/personal-ax-designer-ai-exposure\.pdf/, 'the static PDF must have a stable public URL')
assert.match(panelSource, /download="personal-ax-designer-ai-exposure\.pdf"/, 'the report action must request a direct browser download')
assert.match(generatorSource, /chromium\.launch\(\{ headless: true/, 'the asset must be generated by native Chromium')
assert.match(generatorSource, /page\.pdf\(/, 'the asset generator must write a real PDF')
assert.match(generatorSource, /pdfReport=designer-ai-exposure/, 'the generator must render the long designer report')
assert.match(generatorSource, /closedDetails/, 'the generator must verify that expanded report details are present')
assert.match(generatorSource, /displayHeaderFooter: false/, 'the PDF must not have browser URL/date print headers')
assert.match(appSource, /pdfReportId === 'designer-ai-exposure'/, 'the app needs an isolated render mode for the build-time report')

console.log('Personal AX PDF download contract valid: the long designer report links to a build-time Chromium PDF asset; normal reports retain client html2pdf export.')
